// Database adapters with one small async interface, so the same Store runs on
// SQLite (local default, file or ':memory:') and Postgres (hosted, e.g.
// Supabase on Vercel):
//   all(sql, params) -> rows        get(sql, params) -> row | undefined
//   run(sql, params) -> { changes } insert(sql, params) -> new id
//   tx(fn) -> runs fn() in a transaction; queries made inside it (on this
//   same object) join the transaction.
// SQL is written once with `?` placeholders and unqualified table names.

import { AsyncLocalStorage } from 'node:async_hooks';
import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

export const PG_SCHEMA = 'nurse_schedule';
const TABLES = ['facilities', 'nurses', 'shifts', 'series', 'series_exceptions', 'requirements'];

const SQLITE_SCHEMA = `
CREATE TABLE IF NOT EXISTS facilities (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  timezone TEXT NOT NULL,
  color TEXT,
  active INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS nurses (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1
);
-- One-time assignments (including coverage assignments).
CREATE TABLE IF NOT EXISTS shifts (
  id INTEGER PRIMARY KEY,
  facility_id INTEGER NOT NULL REFERENCES facilities(id),
  nurse_id INTEGER REFERENCES nurses(id),
  start_date TEXT NOT NULL,
  end_date TEXT NOT NULL,
  start_time TEXT,
  end_time TEXT,
  hours_specified INTEGER NOT NULL DEFAULT 1,
  type TEXT NOT NULL,
  covering_for_id INTEGER REFERENCES nurses(id),
  notes TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL,
  vacated INTEGER NOT NULL DEFAULT 0,
  covers_ref TEXT,
  created_at TEXT,
  updated_at TEXT
);
CREATE INDEX IF NOT EXISTS shifts_date ON shifts(start_date);
CREATE INDEX IF NOT EXISTS shifts_covers ON shifts(covers_ref);
-- Recurring schedules: one row per series, never one row per occurrence.
CREATE TABLE IF NOT EXISTS series (
  id INTEGER PRIMARY KEY,
  facility_id INTEGER NOT NULL REFERENCES facilities(id),
  nurse_id INTEGER REFERENCES nurses(id),
  start_time TEXT,
  end_time TEXT,
  end_offset INTEGER NOT NULL DEFAULT 0,
  hours_specified INTEGER NOT NULL DEFAULT 1,
  type TEXT NOT NULL,
  covering_for_id INTEGER REFERENCES nurses(id),
  notes TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL,
  start_date TEXT NOT NULL,
  interval_weeks INTEGER NOT NULL DEFAULT 1,
  weekdays TEXT NOT NULL,
  end_type TEXT NOT NULL DEFAULT 'never',
  until_date TEXT,
  count INTEGER,
  created_at TEXT,
  updated_at TEXT
);
-- Per-occurrence exceptions: cancelled or modified (overrides JSON).
CREATE TABLE IF NOT EXISTS series_exceptions (
  id INTEGER PRIMARY KEY,
  series_id INTEGER NOT NULL REFERENCES series(id) ON DELETE CASCADE,
  occurrence_date TEXT NOT NULL,
  cancelled INTEGER NOT NULL DEFAULT 0,
  overrides TEXT NOT NULL DEFAULT '{}',
  UNIQUE(series_id, occurrence_date)
);
CREATE TABLE IF NOT EXISTS requirements (
  id INTEGER PRIMARY KEY,
  facility_id INTEGER NOT NULL REFERENCES facilities(id) ON DELETE CASCADE,
  label TEXT NOT NULL DEFAULT '',
  weekdays TEXT NOT NULL,
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  min_nurses INTEGER NOT NULL DEFAULT 1,
  active INTEGER NOT NULL DEFAULT 1
);
`;

// Postgres: same columns, identity keys, everything inside its own schema.
// The schema is not exposed through Supabase's public data API.
const PG_DDL = `
CREATE SCHEMA IF NOT EXISTS ${PG_SCHEMA};
${SQLITE_SCHEMA
    .replace(/id INTEGER PRIMARY KEY/g, 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/CREATE TABLE IF NOT EXISTS (\w+)/g, `CREATE TABLE IF NOT EXISTS ${PG_SCHEMA}.$1`)
    .replace(/REFERENCES (\w+)\(/g, `REFERENCES ${PG_SCHEMA}.$1(`)
    .replace(/CREATE INDEX IF NOT EXISTS (\w+) ON (\w+)/g, `CREATE INDEX IF NOT EXISTS $1 ON ${PG_SCHEMA}.$2`)}
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    EXECUTE 'REVOKE ALL ON SCHEMA ${PG_SCHEMA} FROM anon, authenticated';
  END IF;
END $$;
`;

export function isPostgresUrl(target) {
  return typeof target === 'string' && /^postgres(ql)?:\/\//.test(target);
}

export async function openDb(target) {
  return isPostgresUrl(target) ? openPostgres(target) : openSqlite(target);
}

// --- SQLite ------------------------------------------------------------------

async function openSqlite(file) {
  const { DatabaseSync } = await import('node:sqlite');
  if (file !== ':memory:') mkdirSync(dirname(file), { recursive: true });
  const raw = new DatabaseSync(file);
  raw.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON;');
  raw.exec(SQLITE_SCHEMA);

  // One connection: transactions are serialised and other queries wait for
  // an open transaction to finish so they never run inside it by accident.
  const inTx = new AsyncLocalStorage();
  let lock = Promise.resolve();
  const ready = () => (inTx.getStore() ? null : lock);
  const stmt = (sql) => raw.prepare(sql);

  return {
    dialect: 'sqlite',
    async all(sql, params = []) { await ready(); return stmt(sql).all(...params); },
    async get(sql, params = []) { await ready(); return stmt(sql).get(...params); },
    async run(sql, params = []) { await ready(); return { changes: Number(stmt(sql).run(...params).changes) }; },
    async insert(sql, params = []) { await ready(); return Number(stmt(`${sql} RETURNING id`).get(...params).id); },
    async tx(fn) {
      if (inTx.getStore()) return fn();
      const prev = lock;
      let release;
      lock = new Promise((r) => { release = r; });
      await prev;
      try {
        raw.exec('BEGIN');
        try {
          const result = await inTx.run(true, fn);
          raw.exec('COMMIT');
          return result;
        } catch (e) {
          raw.exec('ROLLBACK');
          throw e;
        }
      } finally {
        release();
      }
    },
    async close() { await lock; raw.close(); },
  };
}

// --- Postgres ----------------------------------------------------------------

function toPg(sql) {
  let i = 0;
  return sql
    .replace(/\?/g, () => `$${++i}`)
    .replace(new RegExp(`\\b(${TABLES.join('|')})\\b`, 'g'), `${PG_SCHEMA}.$1`);
}

async function openPostgres(url) {
  const { default: pg } = await import('pg');
  // Hosted providers (Supabase pooler) present certificates Node can't verify
  // with its default CA list; the connection is still encrypted.
  const u = new URL(url);
  u.searchParams.delete('sslmode');
  u.searchParams.delete('supa');
  const local = ['localhost', '127.0.0.1'].includes(u.hostname);
  const pool = new pg.Pool({
    connectionString: u.toString(),
    ssl: local ? false : { rejectUnauthorized: false },
    max: Number(process.env.PG_POOL_MAX) || 3,
    idleTimeoutMillis: 10000,
  });
  const txClient = new AsyncLocalStorage();
  const q = async (sql, params) => {
    const client = txClient.getStore() || pool;
    return client.query(toPg(sql), params);
  };

  // Create tables on first use. The advisory lock keeps concurrent cold
  // starts from racing each other.
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock(727401)');
    await client.query(PG_DDL);
    await client.query('COMMIT');
  } catch (e) {
    await client.query('ROLLBACK').catch(() => {});
    throw e;
  } finally {
    client.release();
  }

  return {
    dialect: 'postgres',
    async all(sql, params = []) { return (await q(sql, params)).rows; },
    async get(sql, params = []) { return (await q(sql, params)).rows[0]; },
    async run(sql, params = []) { return { changes: (await q(sql, params)).rowCount }; },
    async insert(sql, params = []) { return Number((await q(`${sql} RETURNING id`, params)).rows[0].id); },
    async tx(fn) {
      if (txClient.getStore()) return fn();
      const c = await pool.connect();
      try {
        await c.query('BEGIN');
        const result = await txClient.run(c, fn);
        await c.query('COMMIT');
        return result;
      } catch (e) {
        await c.query('ROLLBACK').catch(() => {});
        throw e;
      } finally {
        c.release();
      }
    },
    async close() { await pool.end(); },
  };
}
